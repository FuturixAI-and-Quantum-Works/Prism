import DOMPurify, { type Config } from 'dompurify'

const editorHtmlConfig = {
  ALLOWED_TAGS: [
    'a',
    'b',
    'blockquote',
    'br',
    'code',
    'col',
    'colgroup',
    'del',
    'div',
    'em',
    'h1',
    'h2',
    'h3',
    'h4',
    'h5',
    'h6',
    'hr',
    'i',
    'img',
    'ins',
    'li',
    'mark',
    'ol',
    'p',
    'pre',
    's',
    'span',
    'strike',
    'strong',
    'sub',
    'sup',
    'table',
    'tbody',
    'td',
    'tfoot',
    'th',
    'thead',
    'tr',
    'u',
    'ul',
  ],
  ALLOWED_ATTR: [
    'alt',
    'class',
    'colspan',
    'data-placeholder-id',
    'data-type',
    'height',
    'href',
    'rel',
    'rowspan',
    'src',
    'style',
    'target',
    'title',
    'width',
  ],
  ALLOW_DATA_ATTR: false,
  FORBID_TAGS: [
    'button',
    'embed',
    'form',
    'iframe',
    'input',
    'math',
    'object',
    'select',
    'style',
    'svg',
    'textarea',
  ],
} satisfies Config

export function sanitizeEditorHtml(html: string): string {
  return DOMPurify.sanitize(html, editorHtmlConfig)
}
